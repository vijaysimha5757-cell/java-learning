public class Loops{
    public static void main(String[] args) {
        for (int i = 1; i <= 10; i++) {
            
            System.out.print(i); 
            
            System.out.print(i +" ");
            
            System.out.print(i + 5 +" ");

            System.out.println(i);
            
        }
    }
}